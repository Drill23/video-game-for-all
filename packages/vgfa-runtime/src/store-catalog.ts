export type StoreItemAvailability = 'free-playable' | 'bring-your-rom';

export interface StoreGame {
  id: string;
  title: string;
  consoleId: ConsoleId;
  year: number;
  developer: string;
  genre: string;
  rating: number; // 0..10
  players: string;
  featuredRank?: number; // 1..20 para seção "Mais Jogados"
  serial?: string; // Ex.: SLUS-21678
  sizeEstimate: string;
  coverUrl: string;
  availability: StoreItemAvailability;
  /** Preenchido apenas para títulos 100% livres / open-source jogáveis em 1 clique. */
  freeRomUrl?: string;
  freeRomFilename?: string;
  searchHint: string;
  synopsisPt: string;
  /** Opcional: se ausente, `getSynopsis` cai para `synopsisPt`. */
  synopsisEn?: string;
  /** Opcional: se ausente, `getSynopsis` cai para `synopsisPt`. */
  synopsisEs?: string;
  /** Publicadora (ex.: Sony Computer Entertainment). */
  publisher?: string;
  /** Etiquetas de busca/filtro (ex.: ['Luta','Anime','Multijogador']). */
  tags?: string[];
  /** Modos de jogo em PT-BR (ex.: ['Campanha','Versus local 2P']). */
  modesPt?: string[];
  /** Média de horas para terminar a campanha principal. */
  playtimeHours?: number;
  /** 2–3 frases curtas sobre o que torna o jogo especial. */
  highlightsPt?: string[];
  /** Classificação indicativa brasileira aproximada. */
  ageRating?: 'L' | '10' | '12' | '14' | '16' | '18';
  /** Franquia a que o jogo pertence (ex.: 'Final Fantasy'). */
  franchise?: string;
  /** Posição no ranking do console (1 = melhor). */
  topRank?: number;
}

/** Sinopse no idioma pedido; cai para `synopsisPt` quando não houver tradução. */
export function getSynopsis(game: StoreGame, lang: string): string {
  const text = lang === 'en' ? game.synopsisEn : lang === 'es' ? game.synopsisEs : undefined;
  return text && text.trim() ? text : game.synopsisPt;
}

